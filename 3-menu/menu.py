category = input("Выберите категорию (Напиток, Суп, Десерт): ")

if category == "Напиток":
    choice = input("Выберите напиток (Чай, Кофе, Сок): ")
elif category == "Суп":
    choice = input("Выберите суп (Борщ, Щи, Суп-пюре): ")
elif category == "Десерт":
    choice = input("Выберите десерт (Торт, Мороженое, Фрукты): ")
else:
    print("Выбранная категория отсутствует в меню")
    choice = None

match choice:
    case "Чай":
        print("Цена: 50 рублей")
    case "Кофе":
        print("Цена: 100 рублей")
    case "Сок":
        print("Цена: 80 рублей")
    case "Борщ":
        print("Цена: 150 рублей")
    case "Щи":
        print("Цена: 120 рублей")
    case "Суп-пюре":
        print("Цена: 130 рублей")
    case "Торт":
        print("Цена: 200 рублей")
    case "Мороженое":
        print("Цена: 90 рублей")
    case "Фрукты":
        print("Цена: 70 рублей")
    case _:
        print("Выбранный вариант отсутствует в меню")